/** Имя генерала по двум случайным числам 0..1 (вызывающий берёт их из своего генератора). */
export function generalNameFor(country: string, a: number, b: number): string {
  const c = cultureOf(country);
  const first = c.male[Math.floor(a * c.male.length) % c.male.length];
  if (c.noLast) {
    const second = c.male[Math.floor(b * c.male.length) % c.male.length];
    return second === first ? first : `${first} ${second}`;
  }
  const last = c.last[Math.floor(b * c.last.length) % c.last.length];
  return c.lastFirst ? `${last} ${first}` : `${first} ${last}`;
}
